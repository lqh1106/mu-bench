def _environment(
    domain: str,
    fixture_id: str,
    users: list[UserProfile],
    resources: list[str],
    tools: list[str],
    *rules: str,
) -> EnvironmentBinding:
    return EnvironmentBinding(
        domain=domain,
        fixture_id=fixture_id,
        principals=[user.user_id for user in users],
        resources=resources,
        tool_names=tools,
        policy_extension=[
            "Treat every voice as a separate principal on one shared microphone.",
            "Backchannels, corrections, side-talk, and consent changes take effect when spoken.",
            "A group organizer does not automatically control every adult participant.",
            "Complete deadline-bound reads or actions before their named event; do not wait for the room to become silent.",
            "After a consequential tool result, report the outcome aloud to the affected user in an understandable form.",
            *rules,
        ],
    )


def _case(
    *,
    case_id: str,
    title: str,
    summary: str,
    domain: str,
    users: list[UserProfile],
    resources: list[str],
    tool_names: list[str],
    events: list[ScriptedEvent],
    expected_tools: list[ExpectedToolAction],
    assertions: list[CapabilityAssertion],
    states: list[EnvironmentStateAssertion],
    timings: list[TimingRequirement],
    tier: CaseDifficulty,
    speech: SpeechCondition,
    source_patterns: list[str],
    anti_wait: list[str],
    disfluencies: list[str] | None = None,
    audio_conditions: list[str] | None = None,
    comprehension: list[str] | None = None,
) -> MultiUserVoiceCase:
    first_goal = users[0].goals[0].goal_id
    relations = [
        _relation(first_goal, user.goals[0].goal_id, GoalRelationType.PARTIALLY_ALIGNED)
        for user in users[1:]
    ]
    expected_tools = [
        expected.model_copy(update={"before_event_anchor": "start"})
        if expected.before_event_id is not None
        else expected
        for expected in expected_tools
    ]
    return MultiUserVoiceCase(
        case_id=case_id,
        title=title,
        summary=summary,
        benchmark_version="v0.5",
        capability_tags=[
            domain,
            "multi_user",
            "full_duplex",
            "anti_wait",
            *source_patterns,
        ],
        identity_setup=[
            "Each enrolled user speaks their participant ID, display name, role, and initially active permissions in their stable task voice.",
            "Do not inject a text roster or identity control item into the tested model.",
            "Require report_speaker_attribution(speaker, addressee, thread, confidence) for every task utterance.",
        ],
        permission_setup=[
            "Permissions are action- and resource-scoped per speaker.",
            "Spoken correction, consent, delegation, and revocation update the current decision point.",
        ],
        provenance=BenchmarkProvenance(
            source_benchmarks=["Full-Duplex-Bench v3", "tau-Voice"],
            source_patterns=source_patterns,
            adaptation_summary=(
                "Adds multiple persistent voice identities, speaker-scoped authority, "
                "causal deadlines, and mandatory spoken outcome rendering."
            ),
        ),
        difficulty=DifficultyProfile(
            tier=tier,
            speech_condition=speech,
            participant_band="small_2_3" if len(users) <= 3 else "large_4_6",
            disfluency_types=disfluencies or [],
            audio_conditions=audio_conditions or [],
            comprehension_challenges=comprehension or [],
        ),
        anti_wait_constraints=anti_wait,
        assistant_activation=AssistantActivationProtocol(
            assistant_name="Nova",
            caller_user_id=users[0].user_id,
            utterance_template="Hey {assistant_name}, we need your help.",
        ),
        environment=_environment(
            domain,
            f"{case_id}_fixture",
            users,
            resources,
            tool_names,
        ),
        users=users,
        goal_relations=relations,
        events=events,
        expected_tool_actions=expected_tools,
        timing_requirements=timings,
        capability_assertions=assertions,
        state_assertions=states,
        final_success_conditions=[
            "All deadline-bound tools occur in the correct causal window and under the actual speaker.",
            "Corrections, revocations, backchannels, and side-talk are routed without collapsing speakers or threads.",
            "The assistant speaks the final result to the affected user and repairs comprehension when requested.",
        ],
    )


def _participant(
    user_id: str,
    name: str,
    role: str,
    goal: str,
    *,
    actions: list[str] | None = None,
    resources: list[str] | None = None,
    disposition: GoalDisposition = GoalDisposition.FULFILL,
    accent: str = "General American",
    lexical_style: list[str] | None = None,
    hearing: str = "typical",
    comprehension: str = "typical",
    behavior: list[str] | None = None,
    interrupt: float = 0.3,
) -> UserProfile:
    permissions = []
    if actions:
        permissions.append(_grant(f"grant_{user_id}", actions, resources or ["*"]))
    return _user(
        user_id,
        name,
        role,
        goals=[_goal(f"goal_{user_id}", goal, disposition, priority=5)],
        permissions=permissions,
        private_knowledge=[goal],
        accent=accent,
        lexical_style=lexical_style,
        hearing_profile=hearing,
        comprehension_profile=comprehension,
        behavior_rules=behavior,
        interrupt_tendency=interrupt,
        speaking_style="stable conversational voice; preserve fillers and self-corrections",
    )


def _common_assertions(
    prefix: str,
    update_event: str,
    result_description: str,
    *,
    side_event: str | None = None,
) -> list[CapabilityAssertion]:
    assertions = [
        _capability(
            f"{prefix}_repair",
            CapabilityCategory.TARGETED_REPAIR,
            "Integrate the latest speaker-scoped correction or consent change.",
            "Stop or revise obsolete output and continue with the corrected state without restarting the entire conversation.",
            update_event,
        ),
        _capability(
            f"{prefix}_spoken_result",
            CapabilityCategory.RESPONSE_RENDERING,
            result_description,
            "State the actual tool outcome aloud, address the affected user, and do not claim success before the tool result.",
            update_event,
        ),
    ]
    if side_event:
        assertions.append(
            _capability(
                f"{prefix}_side_routing",
                CapabilityCategory.ADDRESSEE,
                "Keep side-talk or a backchannel from becoming a new command.",
                "Attribute it to the correct speaker and addressee without changing the active task.",
                side_event,
            )
        )
    return assertions


